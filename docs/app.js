const htmlLang = { it: "it", en: "en", zh: "zh-Hans" };
let lang = "it";
let run = 0;

function apply(next) {
  lang = next;
  document.documentElement.lang = htmlLang[next];
  document.title = next === "en"
    ? "AirplaneAI — offline chat, on the phone"
    : next === "zh"
      ? "AirplaneAI — 离线聊天，留在手机里"
      : "AirplaneAI — chat offline, a bordo del telefono";
  const table = copy[next];
  document.querySelectorAll("[data-i]").forEach((node) => {
    const value = table[node.dataset.i];
    if (value != null) node.textContent = value;
  });
  document.querySelectorAll(".langs button").forEach((button) => {
    button.setAttribute("aria-pressed", button.dataset.lang === next ? "true" : "false");
  });
  startChat();
}

function bubble(role, text, caret) {
  const el = document.createElement("div");
  el.className = `bubble ${role}`;
  el.textContent = text;
  if (caret) {
    const mark = document.createElement("span");
    mark.className = "caret";
    el.append(mark);
  }
  return el;
}

function startChat() {
  const thread = document.getElementById("thread");
  const table = copy[lang];
  const token = ++run;
  thread.replaceChildren(
    bubble("system", table.system),
    bubble("user", table.user),
  );
  const reply = bubble("assistant", "", true);
  thread.append(reply);
  const reduced = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
  if (reduced) {
    reply.textContent = table.assistant;
    return;
  }
  let i = 0;
  const tick = () => {
    if (token !== run) return;
    i += 1;
    reply.textContent = table.assistant.slice(0, i);
    if (i < table.assistant.length) {
      reply.append(Object.assign(document.createElement("span"), { className: "caret" }));
      window.setTimeout(tick, 28);
    }
  };
  window.setTimeout(tick, 400);
}

document.querySelectorAll(".langs button").forEach((button) => {
  button.addEventListener("click", () => apply(button.dataset.lang));
});

const horizon = document.getElementById("horizon");
const ball = document.getElementById("ball");
const motionOk = !window.matchMedia("(prefers-reduced-motion: reduce)").matches;
if (motionOk) {
  window.addEventListener("pointermove", (event) => {
    const x = event.clientX / window.innerWidth - 0.5;
    const y = event.clientY / window.innerHeight - 0.5;
    horizon.style.transform = `rotate(${x * -6}deg) translateY(${y * 18}px)`;
    ball.style.transform = `translate(${x * 10}px, ${y * 8}px)`;
  });
  const alt = document.getElementById("alt");
  window.setInterval(() => {
    const value = 380 + Math.round(Math.sin(Date.now() / 900) * 30);
    alt.textContent = String(value);
  }, 700);
}

apply("it");
